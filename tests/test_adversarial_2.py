def test_homological_variable_extraction_indexed():
    """Adversarial check for homological solver's variable extraction.
    
    The existing implementation uses regex `re.findall(r'[a-z]', elem)` which only
    extracts single lowercase letters. For an indexed variable like `x_1`, it extracts
    only `x`, but leaves `x_1` in the matrix content. This causes Macaulay2 to raise
    a syntax/type error because `x_1` is treated as a subscripted variable that has no
    operations defined on it in the ring.
    
    This test verifies that calling the solver with `x_1` raises a `ValueError` due to
    the new variable name validation.
    """
    stabilizer_matrix = [["x_1 - 1"]]
    with pytest.raises(ValueError):
        compute_ext_krull(stabilizer_matrix, qudit_dim=2)


def test_homological_variable_extraction_multi_char():
    """Adversarial check for homological solver's variable extraction.
    
    When variable names have multiple characters (e.g. `xx`), the regex only extracts `x`.
    Since `xx` is not declared in the Macaulay2 ring, Macaulay2 raises a symbol undefined
    error.
    
    This test verifies that calling the solver with `xx` raises a `ValueError` due to
    the new variable name validation.
    """
    stabilizer_matrix = [["xx - 1"]]
    with pytest.raises(ValueError):
        compute_ext_krull(stabilizer_matrix, qudit_dim=2)


def test_grobner_quotient_size_bug():
    """Adversarial check for Gröbner solver's quotient size calculation.
    
    In `count_quotient_size`, if the quotient ring is finite but the Gröbner basis contains
    no generators of the form `1 * v^k` (where the coefficient is exactly 1), it raises
    `ValueError("Quotient ring is infinite.")` incorrectly.
    
    For `qudit_dim = 4` and the stabilizer matrix `[["2*x - 2", "0"]]`, the quotient ring
    is finite (size 8), but the Gröbner basis over Z contains `2*x - 2` and `4`. Since
    there is no generator of the form `1 * x^k`, `count_quotient_size` raises `ValueError`
    representing the finiteness check bug.
    """
    stabilizer_matrix = [["2*x - 2", "0"]]
    result = compute_gsd_and_periodicity(stabilizer_matrix, Lx=2, Ly=2, qudit_dim=4)
    assert result["gsd"] == 4096
    assert result["fusion_rules"] == "infinite"


def test_grobner_inverse_replacement_bug():
    """Adversarial check for Gröbner solver's inverse variable replacement.
    
    The solver performs `entry.strip().replace("t", "x").replace("u", "y")` on all
    matrix elements. This treats the shift-inverse variable `t` as if it were `x`.
    For a non-symmetric/asymmetric polynomial like `x^2 + t` mod 2, the actual ideal
    with `x*t - 1` is generated by `x^3 + 1` (since `t = x^-1`), which has periodicity
    `l_x = 3`. However, the substitution reduces it to `x^2 + x = x*(x + 1) = x + 1`
    which gives periodicity `l_x = 1`.
    
    This test demonstrates the bug where the solver returns `l_x = 1` instead of `3`.
    """
    stabilizer_matrix = [["x^2 + t", "0"]]
    result = compute_gsd_and_periodicity(stabilizer_matrix, Lx=3, Ly=3, qudit_dim=2)
    
    assert result["periodicities"]["l_x"] == 3


def test_hoca_unknown_variables():
    """Adversarial check for HOCA solver's handling of unknown variables.
    
    The HOCA solver only supports variables `x` and `y`. If the input polynomial `poly_g`
    contains other variables (like `z`), they are not mapped to `x` or `y`, so their
    powers are evaluated as 0, effectively treating them as constant `1` (or reducing
    mod 2).
    
    This test verifies that calling the solver with `z` raises a `ValueError` due to
    the symbol validation.
    """
    with pytest.raises(ValueError):
        solve_sset_fusion("1 + x", "z")


def test_hoca_non_existent_fusion_class():
    """Adversarial check for HOCA solver's handling of non-existent fusion classes.
    
    If the class fusion expression refers to a class name (e.g. `beta_{x, 3}`) that is
    not generated by the model's divisor classes (e.g. the model `1 + x` only has
    divisor classes `alpha` and `beta_{x, 1}`), the solver should raise a ValueError.
    """
    with pytest.raises(ValueError):
        solve_sset_fusion("1 + x", "beta_{x, 3}")


def test_homological_invalid_qudit_dims():
    """Checks validation checks for qudit dimension boundaries in the homological solver."""
    stabilizer = [["x - 1", "0"], ["0", "y - 1"]]
    
    # Under limit (qudit_dim < 2)
    with pytest.raises(ValueError):
        compute_ext_krull(stabilizer, qudit_dim=1)
        
    # Non-prime qudit_dim (M2 supports ZZ/p where p is prime)
    with pytest.raises(ValueError):
        compute_ext_krull(stabilizer, qudit_dim=4)
        
    # Extremely large qudit_dim (> 100,000)
    with pytest.raises(ValueError):
        compute_ext_krull(stabilizer, qudit_dim=100001)
