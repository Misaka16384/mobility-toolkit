"""Boundary gauge generator filtering and final independence pruning."""

from __future__ import annotations

import numpy as np

from mobility_toolkit.boundary_gauge.algebra.support import get_support_weight
from mobility_toolkit.boundary_gauge.arithmetic.membership import (
    FieldSpanTester,
    ZdSpanTester,
    _normalize_rows,
    is_prime_int,
)
from mobility_toolkit.boundary_gauge.geometry.translations import (
    translational_duplicate_map_2d,
    translational_duplicate_map_3d,
)


def _span_tester(rows: np.ndarray, d: int) -> FieldSpanTester | ZdSpanTester:
    return FieldSpanTester(rows, d) if is_prime_int(d) else ZdSpanTester(rows, d)


def _weight_ordered_rows(rows: np.ndarray, d: int) -> list[np.ndarray]:
    normalized = _normalize_rows(rows, d)
    return sorted(normalized, key=lambda op: (get_support_weight(op), tuple(int(x) for x in op)))


def filter_boundary_gauge_operators_2d(
    O_w_matrix: np.ndarray,
    S_mat: np.ndarray,
    Lx: int,
    Ly: int,
    q: int,
    d: int,
) -> tuple[np.ndarray, np.ndarray]:
    """Keep boundary candidates not generated by bulk rows and previous x-translates."""
    M2 = _normalize_rows(S_mat, d)
    tester = _span_tester(M2, d)
    raw_ops: list[np.ndarray] = []

    for op in _weight_ordered_rows(O_w_matrix, d):
        if tester.contains(op):
            continue

        raw_ops.append(op.copy() % d)
        translated = translational_duplicate_map_2d(
            op,
            Lx,
            Ly,
            q,
            d,
            max_tx=Lx,
            max_ty=0,
            retain_full_ops=True,
            retain_truncated_ops=False,
        )
        if translated.shape[0] > 0:
            M2 = _normalize_rows(np.vstack([M2, translated]) % d, d)
            tester = _span_tester(M2, d)

    raw = np.array(raw_ops, dtype=int) if raw_ops else np.empty((0, O_w_matrix.shape[1]), dtype=int)
    return M2, raw


