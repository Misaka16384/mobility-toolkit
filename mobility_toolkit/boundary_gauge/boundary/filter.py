def prune_boundary_gauge_ops_2d(
    ops: np.ndarray,
    S_mat: np.ndarray,
    Lx: int,
    Ly: int,
    q: int,
    d: int,
) -> np.ndarray:
    """Remove generators that become redundant after support reduction."""
    ops = _normalize_rows(ops, d)
    if ops.shape[0] == 0:
        return ops

    current = _normalize_rows(S_mat, d)
    tester = _span_tester(current, d)
    kept: list[np.ndarray] = []

    for op in _weight_ordered_rows(ops, d):
        if tester.contains(op):
            continue

        kept.append(op.copy() % d)
        translated = translational_duplicate_map_2d(
            op,
            Lx,
            Ly,
            q,
            d,
            max_tx=Lx,
            max_ty=0,
            retain_full_ops=True,
            retain_truncated_ops=False,
        )
        if translated.shape[0] > 0:
            current = _normalize_rows(np.vstack([current, translated]) % d, d)
            tester = _span_tester(current, d)

    if not kept:
        return np.empty((0, ops.shape[1]), dtype=int)
    return np.array(kept, dtype=int) % d


