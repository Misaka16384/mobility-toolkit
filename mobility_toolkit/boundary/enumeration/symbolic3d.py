"""Bounded symbolic candidate enumeration for three-dimensional boundaries.

This is the deliberately restricted E3 research layer.  Its input is a
*caller-supplied* free module over a two-variable tangent Laurent ring,
together with an anti-hermitian quasi-symplectic pairing.  Within a finite
coefficient-support box it enumerates canonical ``F_p``-row spaces with a
bounded number of seed generators.  Each seed presentation generates a
Laurent submodule, and isotropy is checked exactly as a Laurent-polynomial
identity.

The finite search domain is not a thermodynamic classification:

* different bounded seed presentations can generate the same Laurent
  submodule because general Laurent-polynomial generator changes are not
  solved here;
* saturation, anomaly tests, local Hamiltonian completion, residual boundary
  order, and bulk-termination maps are unsupported;
* ``bounded_exact`` means only that every canonical seed presentation in the
  recorded finite domain was visited.

Two equivalence relations are implemented.  ``raw`` quotients only constant
``GL(k,F_p)`` generator changes by using a unique RREF basis.  ``translation``
additionally identifies the explicit subset generated by a common tangent
monomial translation which keeps all coefficients inside the search box.
Neither relation is called physical, Clifford, stable-ancilla, stacking, or
foliated equivalence.
"""

