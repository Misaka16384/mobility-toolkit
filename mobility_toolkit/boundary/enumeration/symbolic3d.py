def _monomials(
    bounds: Sequence[Tuple[int, int]],
) -> Tuple[Exponent, ...]:
    return tuple(
        tuple(exponents)
        for exponents in itertools.product(
            *(range(lower, upper + 1) for lower, upper in bounds)
        )
    )


def _rref(rows: Iterable[Sequence[int]], modulus: int) -> CoefficientBasis:
    matrix = [
        [int(value) % modulus for value in row]
        for row in rows
        if any(int(value) % modulus for value in row)
    ]
    if not matrix:
        return ()
    width = len(matrix[0])
    if any(len(row) != width for row in matrix):
        raise ValueError("coefficient rows have inconsistent widths")
    pivot_row = 0
    for column in range(width):
        pivot = next(
            (
                row
                for row in range(pivot_row, len(matrix))
                if matrix[row][column] % modulus
            ),
            None,
        )
        if pivot is None:
            continue
        matrix[pivot_row], matrix[pivot] = matrix[pivot], matrix[pivot_row]
        inverse = pow(matrix[pivot_row][column], modulus - 2, modulus)
        matrix[pivot_row] = [
            value * inverse % modulus for value in matrix[pivot_row]
        ]
        for row in range(len(matrix)):
            if row == pivot_row:
                continue
            coefficient = matrix[row][column] % modulus
            if coefficient:
                matrix[row] = [
                    (left - coefficient * right) % modulus
                    for left, right in zip(matrix[row], matrix[pivot_row])
                ]
        pivot_row += 1
        if pivot_row == len(matrix):
            break
    matrix = [row for row in matrix if any(row)]
    return tuple(tuple(row) for row in matrix)


def _rref_subspaces(
    width: int,
    modulus: int,
    max_dimension: int,
    include_zero: bool,
) -> Iterator[CoefficientBasis]:
    """Yield every RREF basis of dimension at most ``max_dimension`` once."""

    if include_zero:
        yield ()
    for dimension in range(1, min(width, max_dimension) + 1):
        for pivots in itertools.combinations(range(width), dimension):
            free_columns = tuple(
                column for column in range(width) if column not in pivots
            )
            positions = tuple(
                (row, column)
                for row, pivot in enumerate(pivots)
                for column in free_columns
                if column > pivot
            )
            for values in itertools.product(range(modulus), repeat=len(positions)):
                rows = [[0] * width for _ in range(dimension)]
                for row, pivot in enumerate(pivots):
                    rows[row][pivot] = 1
                for (row, column), value in zip(positions, values):
                    rows[row][column] = value
                yield tuple(tuple(row) for row in rows)


def _row_to_vector(
    row: CoefficientRow,
    request: Symbolic3DSearchRequest,
) -> LaurentVector:
    monomials = _monomials(request.exponent_bounds)
    count = len(monomials)
    modulus = request.presentation.coefficient_modulus
    return tuple(
        TangentLaurentPolynomial(
            modulus,
            2,
            tuple(
                TangentLaurentTerm(
                    row[component * count + monomial_index],
                    exponent,
                )
                for monomial_index, exponent in enumerate(monomials)
                if row[component * count + monomial_index] % modulus
            ),
        )
        for component in range(request.presentation.module_rank)
    )


def _zero(modulus: int) -> TangentLaurentPolynomial:
    return TangentLaurentPolynomial(modulus, 2, ())


def _add(
    left: TangentLaurentPolynomial,
    right: TangentLaurentPolynomial,
) -> TangentLaurentPolynomial:
    return TangentLaurentPolynomial(
        left.coefficient_modulus,
        left.tangent_rank,
        left.terms + right.terms,
    )


def _multiply(
    left: TangentLaurentPolynomial,
    right: TangentLaurentPolynomial,
) -> TangentLaurentPolynomial:
    return TangentLaurentPolynomial(
        left.coefficient_modulus,
        left.tangent_rank,
        tuple(
            TangentLaurentTerm(
                left_term.coefficient * right_term.coefficient,
                tuple(
                    a + b
                    for a, b in zip(
                        left_term.exponents,
                        right_term.exponents,
                    )
                ),
            )
            for left_term in left.terms
            for right_term in right.terms
        ),
    )


def _pair(
    left: LaurentVector,
    right: LaurentVector,
    presentation: FreeBoundaryPairingPresentation,
) -> TangentLaurentPolynomial:
    value = _zero(presentation.coefficient_modulus)
    for row, left_entry in enumerate(left):
        for column, right_entry in enumerate(right):
            value = _add(
                value,
                _multiply(
                    _multiply(
                        left_entry.involution(),
                        presentation.pairing_matrix[row][column],
                    ),
                    right_entry,
                ),
            )
    return value


def _pairing_matrix(
    basis: CoefficientBasis,
    request: Symbolic3DSearchRequest,
) -> LaurentPairingMatrix:
    vectors = tuple(_row_to_vector(row, request) for row in basis)
    return tuple(
        tuple(_pair(left, right, request.presentation) for right in vectors)
        for left in vectors
    )


def _translate_basis(
    basis: CoefficientBasis,
    shift: Exponent,
    request: Symbolic3DSearchRequest,
) -> CoefficientBasis:
    monomials = _monomials(request.exponent_bounds)
    index = {exponent: position for position, exponent in enumerate(monomials)}
    count = len(monomials)
    translated = []
    for row in basis:
        output = [0] * len(row)
        for component in range(request.presentation.module_rank):
            for monomial_index, exponent in enumerate(monomials):
                coefficient = row[component * count + monomial_index]
                if not coefficient:
                    continue
                target = tuple(map(operator.add, exponent, shift))
                if target not in index:
                    raise ValueError("translated support leaves the search box")
                output[component * count + index[target]] = coefficient
        translated.append(tuple(output))
    return _rref(translated, request.presentation.coefficient_modulus)


def _translation_key(
    basis: CoefficientBasis,
    request: Symbolic3DSearchRequest,
) -> str:
    if not basis:
        return canonical_hash("symbolic3d-translation-orbit-v1", basis)
    monomials = _monomials(request.exponent_bounds)
    count = len(monomials)
    occupied = []
    for row in basis:
        for component in range(request.presentation.module_rank):
            for index, exponent in enumerate(monomials):
                if row[component * count + index]:
                    occupied.append(exponent)
    minima = tuple(min(point[axis] for point in occupied) for axis in range(2))
    maxima = tuple(max(point[axis] for point in occupied) for axis in range(2))
    shift_ranges = tuple(
        range(lower - minima[axis], upper - maxima[axis] + 1)
        for axis, (lower, upper) in enumerate(request.exponent_bounds)
    )
    orbit = tuple(
        _translate_basis(basis, tuple(shift), request)
        for shift in itertools.product(*shift_ranges)
    )
    canonical = min(canonical_json(item) for item in orbit)
    return canonical_hash("symbolic3d-common-translation-orbit-v1", canonical)


def _equivalence_key(
    basis: CoefficientBasis,
    request: Symbolic3DSearchRequest,
) -> str:
    if request.equivalence is Symbolic3DEquivalence.TRANSLATION:
        return _translation_key(basis, request)
    return canonical_hash("symbolic3d-raw-rref-basis-v1", basis)


def _transcript_hash(
    transcript: Sequence[Symbolic3DTranscriptEntry],
) -> str:
    previous = canonical_hash("symbolic3d-transcript-root-v1", ())
    for index, entry in enumerate(transcript):
        previous = canonical_hash(
            "symbolic3d-transcript-chain-v1",
            {"entry": entry, "index": index, "previous": previous},
        )
    return previous


def _representative_prefix_hash(
    prefix: Sequence[Tuple[str, str]],
) -> str:
    previous = canonical_hash("symbolic3d-representative-prefix-root-v1", ())
    for index, entry in enumerate(prefix):
        previous = canonical_hash(
            "symbolic3d-representative-prefix-chain-v1",
            {"entry": entry, "index": index, "previous": previous},
        )
    return previous


def _output_prefix_hash(prefix: Sequence[str]) -> str:
    previous = canonical_hash("symbolic3d-output-prefix-root-v1", ())
    for index, candidate_hash in enumerate(prefix):
        previous = canonical_hash(
            "symbolic3d-output-prefix-chain-v1",
            {
                "candidate_hash": candidate_hash,
                "index": index,
                "previous": previous,
            },
        )
    return previous


def _checkpoint_hash(checkpoint: Symbolic3DCheckpoint) -> str:
    return canonical_hash(
        "symbolic3d-checkpoint-seal-v1",
        {
            "equivalence_representative_prefix":
                checkpoint.equivalence_representative_prefix,
            "equivalence_representative_prefix_hash":
                checkpoint.equivalence_representative_prefix_hash,
            "output_prefix": checkpoint.output_prefix,
            "output_prefix_hash": checkpoint.output_prefix_hash,
            "request_hash": checkpoint.request_hash,
            "rref_cursor": checkpoint.rref_cursor,
            "total_work": checkpoint.total_work,
            "transcript": checkpoint.transcript,
            "transcript_hash": checkpoint.transcript_hash,
        },
    )


def _seal_checkpoint(
    request_hash: str,
    transcript: Sequence[Symbolic3DTranscriptEntry],
    representatives: Sequence[Tuple[str, str]],
    output_prefix: Sequence[str],
) -> Symbolic3DCheckpoint:
    unsealed = Symbolic3DCheckpoint(
        request_hash=request_hash,
        rref_cursor=len(transcript),
        transcript=tuple(transcript),
        transcript_hash=_transcript_hash(transcript),
        equivalence_representative_prefix=tuple(representatives),
        equivalence_representative_prefix_hash=_representative_prefix_hash(
            representatives
        ),
        output_prefix=tuple(output_prefix),
        output_prefix_hash=_output_prefix_hash(output_prefix),
        total_work=len(transcript),
        checkpoint_hash="",
    )
    return Symbolic3DCheckpoint(
        request_hash=unsealed.request_hash,
        rref_cursor=unsealed.rref_cursor,
        transcript=unsealed.transcript,
        transcript_hash=unsealed.transcript_hash,
        equivalence_representative_prefix=(
            unsealed.equivalence_representative_prefix
        ),
        equivalence_representative_prefix_hash=(
            unsealed.equivalence_representative_prefix_hash
        ),
        output_prefix=unsealed.output_prefix,
        output_prefix_hash=unsealed.output_prefix_hash,
        total_work=unsealed.total_work,
        checkpoint_hash=_checkpoint_hash(unsealed),
    )


def _phase_status(modulus: int) -> Tuple[Symbolic3DPhaseStatus, bool]:
    if modulus % 2:
        return Symbolic3DPhaseStatus.CANONICAL_ODD_PRIME_LIFT, True
    return Symbolic3DPhaseStatus.EVEN_PRIME_REFINEMENT_REQUIRED, False


def _evaluate_basis(
    basis: CoefficientBasis,
    request: Symbolic3DSearchRequest,
    seen_equivalence: Dict[str, str],
) -> Tuple[Symbolic3DTranscriptEntry, Optional[Symbolic3DIsotropicCandidate]]:
    pairing = _pairing_matrix(basis, request)
    pairing_hash = canonical_hash("symbolic3d-laurent-pairing-v1", pairing)
    basis_hash = canonical_hash("symbolic3d-rref-seed-basis-v1", basis)
    isotropic = all(entry.is_zero for row in pairing for entry in row)
    key = _equivalence_key(basis, request) if isotropic else ""
    if not isotropic:
        return (
            Symbolic3DTranscriptEntry(
                basis,
                basis_hash,
                Symbolic3DDecision.NON_ISOTROPIC,
                "",
                pairing_hash,
            ),
            None,
        )
    if key in seen_equivalence:
        return (
            Symbolic3DTranscriptEntry(
                basis,
                basis_hash,
                Symbolic3DDecision.ISOTROPIC_EQUIVALENT,
                key,
                pairing_hash,
            ),
            None,
        )
    phase_status, phase_verified = _phase_status(
        request.presentation.coefficient_modulus
    )
    candidate_hash = canonical_hash(
        "symbolic3d-isotropic-candidate-v1",
        {
            "basis": basis,
            "equivalence": request.equivalence,
            "presentation": request.presentation,
        },
    )
    seen_equivalence[key] = candidate_hash
    candidate = Symbolic3DIsotropicCandidate(
        candidate_hash=candidate_hash,
        coefficient_basis=basis,
        generator_vectors=tuple(
            _row_to_vector(row, request) for row in basis
        ),
        generator_count=len(basis),
        pairing_matrix=pairing,
        equivalence=request.equivalence,
        equivalence_key=key,
        projective_commutation_verified=True,
        phase_status=phase_status,
        phase_lift_available_by_canonical_odd_prime_convention=phase_verified,
        phase_assignment_machine_verified=False,
        phase_assignment_witness_status="not_computed",
    )
    return (
        Symbolic3DTranscriptEntry(
            basis,
            basis_hash,
            Symbolic3DDecision.ISOTROPIC_REPRESENTATIVE,
            key,
            pairing_hash,
        ),
        candidate,
    )


def _replay_transcript(
    request: Symbolic3DSearchRequest,
    transcript: Sequence[Symbolic3DTranscriptEntry],
) -> Tuple[
    Iterator[CoefficientBasis],
    Dict[str, str],
    Tuple[Tuple[str, str], ...],
    Tuple[Symbolic3DIsotropicCandidate, ...],
]:
    """Recompute every recorded decision from the canonical RREF origin."""

    iterator = _rref_subspaces(
        request.coefficient_slot_count,
        request.presentation.coefficient_modulus,
        request.max_generators,
        request.include_zero_submodule,
    )
    seen: Dict[str, str] = {}
    representative_prefix = []
    candidates = []
    replayed = 0
    for recorded in transcript:
        try:
            basis = next(iterator)
        except StopIteration:
            raise ValueError("symbolic3d transcript extends past the RREF domain")
        expected_entry, candidate = _evaluate_basis(basis, request, seen)
        if recorded != expected_entry:
            raise ValueError(
                "symbolic3d transcript decision fails semantic replay"
            )
        replayed += 1
        if candidate is not None:
            representative_prefix.append(
                (candidate.equivalence_key, candidate.candidate_hash)
            )
            candidates.append(candidate)
    if replayed != len(transcript):
        raise ValueError("symbolic3d transcript replay length mismatch")
    return (
        iterator,
        seen,
        tuple(representative_prefix),
        tuple(candidates),
    )


def _resume_state(
    request: Symbolic3DSearchRequest,
    checkpoint: Optional[Symbolic3DCheckpoint],
) -> Tuple[
    Iterator[CoefficientBasis],
    Dict[str, str],
    Tuple[Symbolic3DTranscriptEntry, ...],
    Tuple[Tuple[str, str], ...],
    Tuple[str, ...],
]:
    request_hash = canonical_hash("symbolic3d-search-request-v1", request)
    if checkpoint is None:
        return (
            _rref_subspaces(
                request.coefficient_slot_count,
                request.presentation.coefficient_modulus,
                request.max_generators,
                request.include_zero_submodule,
            ),
            {},
            (),
            (),
            (),
        )
    if not isinstance(checkpoint, Symbolic3DCheckpoint):
        raise TypeError("checkpoint must be Symbolic3DCheckpoint")
    if not checkpoint.structurally_verified:
        raise ValueError("symbolic3d checkpoint seal or prefix chain is invalid")
    if checkpoint.request_hash != request_hash:
        raise ValueError("symbolic3d checkpoint belongs to a different request")
    iterator, seen, representatives, candidates = _replay_transcript(
        request, checkpoint.transcript
    )
    expected_output = tuple(
        candidate.candidate_hash for candidate in candidates
    )
    if representatives != checkpoint.equivalence_representative_prefix:
        raise ValueError(
            "symbolic3d checkpoint representative prefix fails semantic replay"
        )
    if expected_output != checkpoint.output_prefix:
        raise ValueError(
            "symbolic3d checkpoint output prefix fails semantic replay"
        )
    return (
        iterator,
        seen,
        checkpoint.transcript,
        representatives,
        checkpoint.output_prefix,
    )


def verify_symbolic3d_enumeration(
    enumeration: Symbolic3DEnumeration,
) -> bool:
    """Replay decisions and checkpoint prefixes, not just their hash chains."""

    if not isinstance(enumeration, Symbolic3DEnumeration):
        return False
    request = enumeration.request
    certificate = enumeration.certificate
    if not certificate.structurally_verified:
        return False
    if certificate.request_hash != canonical_hash(
        "symbolic3d-search-request-v1", request
    ):
        return False
    if certificate.presentation_hash != canonical_hash(
        "free-boundary-pairing-presentation-v1", request.presentation
    ):
        return False
    try:
        iterator, _, representatives, expected_candidates = _replay_transcript(
            request, certificate.transcript
        )
    except ValueError:
        return False
    representative_hashes = tuple(
        candidate_hash for _, candidate_hash in representatives
    )
    if representative_hashes != certificate.representative_hashes:
        return False
    if representative_hashes != certificate.output_hashes:
        return False
    page_hashes = tuple(
        candidate.candidate_hash for candidate in enumeration.candidates
    )
    if page_hashes != certificate.output_hashes[
        certificate.page_output_start:certificate.page_output_end
    ]:
        return False
    if certificate.page_output_end - certificate.page_output_start != len(
        enumeration.candidates
    ):
        return False
    try:
        next(iterator)
    except StopIteration:
        domain_exhausted = True
    else:
        domain_exhausted = False
    if certificate.rref_seed_domain_complete != domain_exhausted:
        return False
    if certificate.output_complete != domain_exhausted:
        return False
    checkpoint = enumeration.checkpoint
    if domain_exhausted:
        if checkpoint is not None:
            return False
    else:
        if checkpoint is None:
            return False
        try:
            _resume_state(request, checkpoint)
        except (TypeError, ValueError):
            return False
        if checkpoint.transcript != certificate.transcript:
            return False
        if checkpoint.equivalence_representative_prefix != representatives:
            return False
        if checkpoint.output_prefix != certificate.output_hashes:
            return False
    return True


def enumerate_symbolic3d_candidates(
    request: Symbolic3DSearchRequest,
    budget: Symbolic3DBudget = Symbolic3DBudget(),
    checkpoint: Optional[Symbolic3DCheckpoint] = None,
) -> ComputationResult:
    """Enumerate one resumable page of the finite RREF seed domain."""

    if not isinstance(request, Symbolic3DSearchRequest):
        raise TypeError("request must be Symbolic3DSearchRequest")
    if not isinstance(budget, Symbolic3DBudget):
        raise TypeError("budget must be Symbolic3DBudget")
    (
        iterator,
        seen,
        prior_transcript,
        prior_representatives,
        prior_output,
    ) = _resume_state(request, checkpoint)
    transcript = list(prior_transcript)
    representatives = list(prior_representatives)
    output_prefix = list(prior_output)
    page_candidates = []
    page_work = 0
    page_output_start = len(output_prefix)
    exhausted = False
    while (
        page_work < budget.max_seed_presentations
        and len(page_candidates) < budget.max_output_candidates
    ):
        try:
            basis = next(iterator)
        except StopIteration:
            exhausted = True
            break
        entry, candidate = _evaluate_basis(basis, request, seen)
        transcript.append(entry)
        page_work += 1
        if candidate is not None:
            representatives.append(
                (candidate.equivalence_key, candidate.candidate_hash)
            )
            output_prefix.append(candidate.candidate_hash)
            page_candidates.append(candidate)
    if not exhausted:
        try:
            next(iterator)
        except StopIteration:
            exhausted = True
    output_complete = exhausted
    exactness = (
        Exactness.BOUNDED_EXACT if exhausted else Exactness.EXPERIMENTAL
    )
    request_hash = canonical_hash("symbolic3d-search-request-v1", request)
    presentation_hash = canonical_hash(
        "free-boundary-pairing-presentation-v1", request.presentation
    )
    next_checkpoint = (
        None
        if exhausted
        else _seal_checkpoint(
            request_hash,
            transcript,
            representatives,
            output_prefix,
        )
    )
    certificate = Symbolic3DCompletenessCertificate(
        request_hash=request_hash,
        presentation_hash=presentation_hash,
        coefficient_field_complete=True,
        monomial_box_complete=True,
        rref_seed_domain_complete=exhausted,
        output_complete=output_complete,
        seed_presentations_scanned=len(transcript),
        isotropic_seed_presentations=sum(
            entry.decision is not Symbolic3DDecision.NON_ISOTROPIC
            for entry in transcript
        ),
        equivalence_representatives=len(representatives),
        emitted_candidates=len(output_prefix),
        transcript=tuple(transcript),
        transcript_hash=_transcript_hash(transcript),
        representative_hashes=tuple(
            candidate_hash for _, candidate_hash in representatives
        ),
        output_hashes=tuple(output_prefix),
        page_output_start=page_output_start,
        page_output_end=len(output_prefix),
        exactness=exactness,
        implemented_equivalence=(
            "unique RREF modulo constant GL(k,F_p)"
            if request.equivalence is Symbolic3DEquivalence.RAW
            else (
                "unique RREF modulo constant GL(k,F_p), then common tangent "
                "monomial translations remaining inside the coefficient box"
            )
        ),
    )
    enumeration = Symbolic3DEnumeration(
        request=request,
        candidates=tuple(page_candidates),
        certificate=certificate,
        checkpoint=next_checkpoint,
    )
    if not verify_symbolic3d_enumeration(enumeration):
        raise ArithmeticError("symbolic3d transcript replay failed")
    odd_prime_lift_available = (
        request.presentation.coefficient_modulus % 2 == 1
    )
    return ComputationResult(
        operation="boundary.enumerate_symbolic3d_candidates",
        input_data={
            "budget": budget,
            "checkpoint": checkpoint,
            "request": request,
        },
        value=enumeration,
        exactness=exactness,
        assumptions=(
            "caller supplied the full free tangent-Laurent boundary module",
            "coefficient modulus is prime",
            "flat rational boundary in a three-dimensional lattice",
            "two-dimensional free tangent translation lattice",
        ),
        theorem_scope=(
            "Exhaustive only for canonical F_p-RREF seed presentations whose "
            "coefficients lie in the recorded Laurent exponent box and whose "
            "seed rank is at most max_generators. Each seed generates a Laurent "
            "submodule and isotropy is an exact polynomial identity. General "
            "Laurent submodule equality and thermodynamic boundary completeness "
            "do not follow."
        ),
        certificate_level=CertificateLevel.FULL,
        certificate=certificate,
        verification=(
            ("bounded_domain_complete", certificate.bounded_complete),
            ("odd_prime_phase_lift_theorem_available",
                odd_prime_lift_available),
            ("phase_assignment_machine_verified", False),
            ("projective_pairings_exact", True),
            ("semantic_transcript_replay", True),
            ("thermodynamic_completeness_claimed", False),
        ),
        backend_provenance=BackendProvenance(
            backend="internal-exact-finite-field+laurent",
            algorithm="bounded-rref-seed-submodule-isotropy-enumeration",
            version="2",
            parameters=(
                ("equivalence", request.equivalence.value),
                ("max_generators", request.max_generators),
                ("normal", request.boundary_normal.components),
            ),
        ),
        resource_usage=(
            ("cumulative_candidates", len(output_prefix)),
            ("cumulative_seed_presentations", len(transcript)),
            ("page_candidates", len(page_candidates)),
            ("page_seed_presentations", page_work),
        ),
        diagnostics=(
            "Every reported candidate has zero Laurent pairing between all "
            "seed generators, hence between all Laurent translates.",
            (
                "For odd p, an isotropic module admits a canonical-convention "
                "Heisenberg lift, but this operation did not construct or "
                "machine-verify a phase-assignment witness."
                if odd_prime_lift_available
                else (
                    "At p=2 the abstract pairing does not determine a quadratic "
                    "refinement; phase completion is unsupported."
                )
            ),
        ),
        warnings=(
            "A bounded isotropic seed presentation is not a thermodynamic "
            "gapped boundary.",
            "Saturation, anomaly detection, local Hamiltonian completion, "
            "residual boundary order, and bulk termination are unsupported.",
            "Only constant generator changes and the selected optional common "
            "translation quotient are implemented.",
        ),
    )


