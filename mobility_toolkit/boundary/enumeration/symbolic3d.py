@dataclass(frozen=True)
class Symbolic3DSearchRequest:
    """Finite E3 seed-presentation domain for one free boundary module."""

    presentation: FreeBoundaryPairingPresentation
    boundary_normal: PrimitiveNormal
    exponent_bounds: Tuple[Tuple[int, int], ...]
    max_generators: int
    equivalence: Symbolic3DEquivalence = Symbolic3DEquivalence.RAW
    include_zero_submodule: bool = False
    source_lock: Optional[Symbolic3DSourceLock] = None

    SCHEMA_ID = "mobility_toolkit.symbolic3d_search_request.v1"

    def __post_init__(self) -> None:
        if not isinstance(self.presentation, FreeBoundaryPairingPresentation):
            raise TypeError(
                "presentation must be FreeBoundaryPairingPresentation"
            )
        if self.presentation.tangent_rank != 2:
            raise ValueError(
                "symbolic3d requires a two-dimensional tangent Laurent ring"
            )
        if not is_prime(self.presentation.coefficient_modulus):
            raise NotImplementedError(
                "symbolic3d RREF enumeration currently requires a prime "
                "coefficient field"
            )
        if not isinstance(self.boundary_normal, PrimitiveNormal):
            raise TypeError("boundary_normal must be PrimitiveNormal")
        if self.boundary_normal.dimension != 3:
            raise ValueError("symbolic3d requires a three-dimensional normal")
        bounds = tuple(tuple(pair) for pair in self.exponent_bounds)
        if len(bounds) != self.presentation.tangent_rank:
            raise ValueError("one exponent bound is required per tangent axis")
        for pair in bounds:
            if (
                len(pair) != 2
                or isinstance(pair[0], bool)
                or isinstance(pair[1], bool)
                or not isinstance(pair[0], int)
                or not isinstance(pair[1], int)
                or pair[0] > pair[1]
            ):
                raise ValueError(
                    "each exponent bound must be an integer (lower, upper) pair"
                )
        _positive(self.max_generators, "max_generators")
        equivalence = Symbolic3DEquivalence(self.equivalence)
        if self.source_lock is not None:
            if self.source_lock.boundary_normal != self.boundary_normal:
                raise ValueError("source-lock normal differs from request normal")
            if not self.source_lock.full_boundary_module_supplied:
                raise ValueError(
                    "symbolic search requires a supplied full boundary module; "
                    "a primary-only source lock is insufficient"
                )
        object.__setattr__(self, "exponent_bounds", bounds)
        object.__setattr__(self, "equivalence", equivalence)

    @property
    def coefficient_bound(self) -> Tuple[int, int]:
        return (0, self.presentation.coefficient_modulus - 1)

    @property
    def monomial_count(self) -> int:
        count = 1
        for lower, upper in self.exponent_bounds:
            count *= upper - lower + 1
        return count

    @property
    def coefficient_slot_count(self) -> int:
        return self.presentation.module_rank * self.monomial_count

    def to_canonical_dict(self) -> dict:
        return {
            "boundary_normal": self.boundary_normal,
            "coefficient_bound": self.coefficient_bound,
            "coefficient_slot_count": self.coefficient_slot_count,
            "equivalence": self.equivalence,
            "exponent_bounds": self.exponent_bounds,
            "include_zero_submodule": self.include_zero_submodule,
            "max_generators": self.max_generators,
            "monomial_count": self.monomial_count,
            "presentation": self.presentation,
            "schema": self.SCHEMA_ID,
            "source_lock": self.source_lock,
        }


