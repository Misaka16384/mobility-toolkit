"""Project-level installer.

Wires the mobility_toolkit skills + MCP server into AI coding agents:

  - Claude Code   project: .claude/skills/   +  .mcp.json
  - opencode      project: .opencode/skills/ +  opencode.json   (also reads .claude/skills/)
  - Codex         project: .agents/skills/   +  .codex/config.toml
  - Antigravity   project: .agents/skills/   +  .agents/mcp_config.json
                  (Antigravity 2.0; --antigravity-global targets ~/.gemini instead)

All four agents support per-project config, so the default install is fully
project-level. Note `.agents/skills/` is shared by Codex and Antigravity 2.0.
Skills are the primary artifact; the MCP server is wired as the universal
fallback (every supported agent speaks MCP).
"""

import json
import os
import shutil
import sys
from pathlib import Path
from typing import Callable, List, Optional

# --- locations -------------------------------------------------------------
PACKAGE_DIR = Path(__file__).resolve().parent          # .../mobility_toolkit/mobility_toolkit
REPO_ROOT = PACKAGE_DIR.parent                         # repo root (holds skills/)
SKILLS_SRC = REPO_ROOT / "skills"

SKILL_NAMES = [
    "translate_to_algebra",
    "compute_homology_and_mobility",
    "analyze_fusion_interference",
    "query_vector_db",
]

# --- MCP server invocation -------------------------------------------------
MCP_NAME = "mobility_toolkit"
MCP_COMMAND = sys.executable                           # pin the interpreter that has the package
MCP_ARGS = ["-m", "mobility_toolkit.mcp_server"]

PROJECT_TARGETS = ["claude", "codex", "opencode", "antigravity"]  # all support per-project config
ALL_TARGETS = list(PROJECT_TARGETS)

_BOOTSTRAP_MARKER = "mobility_toolkit path bootstrap"
AGENTS_BLOCK_START = "<!-- mobility-toolkit:start -->"
AGENTS_BLOCK_END = "<!-- mobility-toolkit:end -->"

Logger = Callable[[str], None]


# --- skill copying ---------------------------------------------------------
def _bootstrap_header() -> str:
    """A self-locating header injected into copied skill scripts so they can
    `import mobility_toolkit` even when run by a Python that has not pip-installed
    the package (the scripts get copied away from the repo)."""
    return (
        f"# >>> {_BOOTSTRAP_MARKER} (auto-generated by `mobility-toolkit install`) >>>\n"
        f"import sys as _mt_sys\n"
        f"_mt_sys.path.insert(0, r\"{REPO_ROOT}\")\n"
        f"# <<< {_BOOTSTRAP_MARKER} <<<\n\n"
    )


def _copy_skills(dest_root: Path, log: Logger) -> int:
    dest_root.mkdir(parents=True, exist_ok=True)
    count = 0
    for name in SKILL_NAMES:
        src = SKILLS_SRC / name
        if not src.is_dir():
            log(f"  ! skill source missing: {src}")
            continue
        dst = dest_root / name
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        scripts_dir = dst / "scripts"
        if scripts_dir.is_dir():
            for script in scripts_dir.glob("*.py"):
                text = script.read_text(encoding="utf-8")
                if _BOOTSTRAP_MARKER not in text:
                    script.write_text(_bootstrap_header() + text, encoding="utf-8")
        count += 1
    log(f"  + {count} skills -> {dest_root}")
    return count


def _remove_skills(dest_root: Path, log: Logger) -> None:
    removed = 0
    for name in SKILL_NAMES:
        dst = dest_root / name
        if dst.exists():
            shutil.rmtree(dst)
            removed += 1
    if removed:
        log(f"  - removed {removed} skills from {dest_root}")


# --- JSON config helpers ---------------------------------------------------
def _load_json(path: Path) -> dict:
    if path.exists():
        try:
            return json.loads(path.read_text(encoding="utf-8") or "{}")
        except json.JSONDecodeError:
            return {}
    return {}


def _save_json(path: Path, data: dict, log: Logger) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    log(f"  + MCP config -> {path}")


def _json_set_mcp(path: Path, parent_key: str, entry: dict, log: Logger) -> None:
    data = _load_json(path)
    data.setdefault(parent_key, {})[MCP_NAME] = entry
    _save_json(path, data, log)


def _json_unset_mcp(path: Path, parent_key: str, log: Logger) -> None:
    if not path.exists():
        return
    data = _load_json(path)
    if parent_key in data and MCP_NAME in data[parent_key]:
        del data[parent_key][MCP_NAME]
        _save_json(path, data, log)
        log(f"  - removed MCP entry from {path}")


# --- Codex TOML helpers (no tomli_w dependency) ----------------------------
def _toml_block() -> str:
    args_toml = ", ".join(f'"{a}"' for a in MCP_ARGS)
    # single-quoted TOML literal string avoids backslash escaping on Windows paths
    return (
        f"\n[mcp_servers.{MCP_NAME}]\n"
        f"command = '{MCP_COMMAND}'\n"
        f"args = [{args_toml}]\n"
    )


def _merge_codex_toml(path: Path, log: Logger) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    header = f"[mcp_servers.{MCP_NAME}]"
    if header in existing:
        log(f"  = MCP already present in {path}")
        return
    with path.open("a", encoding="utf-8") as f:
        f.write(_toml_block())
    log(f"  + MCP config -> {path} ([mcp_servers.{MCP_NAME}])")


def _remove_codex_toml(path: Path, log: Logger) -> None:
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    header = f"[mcp_servers.{MCP_NAME}]"
    if header not in text:
        return
    lines = text.splitlines(keepends=True)
    out, skipping = [], False
    for line in lines:
        stripped = line.strip()
        if stripped == header:
            skipping = True
            continue
        if skipping and stripped.startswith("[") and stripped.endswith("]"):
            skipping = False
        if not skipping:
            out.append(line)
    path.write_text("".join(out).rstrip() + "\n", encoding="utf-8")
    log(f"  - removed MCP block from {path}")


# --- AGENTS.md managed block ----------------------------------------------
def _agents_block() -> str:
    return (
        f"{AGENTS_BLOCK_START}\n"
        "## mobility_toolkit\n\n"
        "Homological-algebra toolkit for excitation-mobility properties of "
        "translation-invariant stabilizer codes (backed by Macaulay2).\n\n"
        "Skills (SKILL.md) installed under this agent's skills directory:\n"
        "`translate_to_algebra`, `compute_homology_and_mobility`, "
        "`analyze_fusion_interference`, `query_vector_db`.\n\n"
        "Also exposed as MCP server `mobility_toolkit` with tools: "
        "`compute_homology`, `compute_mobility`, `compute_grobner`, "
        "`compute_fusion_interference`, `search_models`.\n\n"
        "Run `mobility-toolkit doctor` to verify the Macaulay2 backend.\n"
        f"{AGENTS_BLOCK_END}"
    )


def _write_agents_md(project: Path, log: Logger) -> None:
    path = project / "AGENTS.md"
    block = _agents_block()
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if AGENTS_BLOCK_START in text and AGENTS_BLOCK_END in text:
            pre = text.split(AGENTS_BLOCK_START)[0].rstrip()
            post = text.split(AGENTS_BLOCK_END, 1)[1].lstrip()
            text = (pre + "\n\n" + block + ("\n\n" + post if post else "\n")).rstrip() + "\n"
        else:
            text = text.rstrip() + "\n\n" + block + "\n"
    else:
        text = "# AGENTS\n\n" + block + "\n"
    path.write_text(text, encoding="utf-8")
    log(f"  + AGENTS.md -> {path}")


def _remove_agents_block(project: Path, log: Logger) -> None:
    path = project / "AGENTS.md"
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    if AGENTS_BLOCK_START in text and AGENTS_BLOCK_END in text:
        pre = text.split(AGENTS_BLOCK_START)[0].rstrip()
        post = text.split(AGENTS_BLOCK_END, 1)[1].lstrip()
        new = (pre + ("\n\n" + post if post else "")).rstrip() + "\n"
        path.write_text(new if new.strip() else "", encoding="utf-8")
        log(f"  - removed AGENTS.md block from {path}")


# --- per-agent installers --------------------------------------------------
def install_claude(project: Path, log: Logger) -> None:
    log("[claude] project-level (.claude/)")
    _copy_skills(project / ".claude" / "skills", log)
    _json_set_mcp(project / ".mcp.json", "mcpServers", {"command": MCP_COMMAND, "args": MCP_ARGS}, log)


def install_opencode(project: Path, log: Logger) -> None:
    log("[opencode] project-level (.opencode/)")
    _copy_skills(project / ".opencode" / "skills", log)
    cfg = project / "opencode.json"
    data = _load_json(cfg)
    data.setdefault("$schema", "https://opencode.ai/config.json")
    data.setdefault("mcp", {})[MCP_NAME] = {
        "type": "local",
        "command": [MCP_COMMAND] + MCP_ARGS,
        "enabled": True,
    }
    _save_json(cfg, data, log)


def install_codex(project: Path, log: Logger) -> None:
    log("[codex] project-level (.agents/, .codex/)")
    _copy_skills(project / ".agents" / "skills", log)
    _merge_codex_toml(project / ".codex" / "config.toml", log)


def install_antigravity(project: Path, log: Logger, use_global: bool = False) -> None:
    if use_global:
        home = Path.home()
        log("[antigravity] GLOBAL ~/.gemini")
        _copy_skills(home / ".gemini" / "skills", log)
        _json_set_mcp(
            home / ".gemini" / "config" / "mcp_config.json",
            "mcpServers",
            {"command": MCP_COMMAND, "args": MCP_ARGS},
            log,
        )
    else:
        log("[antigravity] project-level (.agents/ — shared with Codex skills)")
        _copy_skills(project / ".agents" / "skills", log)
        _json_set_mcp(
            project / ".agents" / "mcp_config.json",
            "mcpServers",
            {"command": MCP_COMMAND, "args": MCP_ARGS},
            log,
        )


_INSTALLERS = {
    "claude": lambda p, log: install_claude(p, log),
    "codex": lambda p, log: install_codex(p, log),
    "opencode": lambda p, log: install_opencode(p, log),
    # antigravity is handled explicitly in run_install (needs the --antigravity-global flag)
}


# --- detection -------------------------------------------------------------
def detect_agents(project: Path) -> List[str]:
    found = []
    if (project / ".claude").exists() or shutil.which("claude"):
        found.append("claude")
    if (project / ".codex").exists() or (project / ".agents").exists() or shutil.which("codex"):
        found.append("codex")
    if (project / ".opencode").exists() or (project / "opencode.json").exists() or shutil.which("opencode"):
        found.append("opencode")
    if (project / ".agents").exists() or (Path.home() / ".gemini").exists() \
            or shutil.which("antigravity") or shutil.which("agy"):
        found.append("antigravity")
    return found


def _resolve_targets(targets: Optional[List[str]], project: Path, log: Logger) -> List[str]:
    if targets and targets != ["all"]:
        return [t for t in targets if t in ALL_TARGETS]
    if targets == ["all"]:
        return list(ALL_TARGETS)
    detected = list(dict.fromkeys(detect_agents(project)))
    chosen = detected or list(PROJECT_TARGETS)
    if detected:
        log(f"Detected agents: {', '.join(detected)}")
    else:
        log("No agents detected; defaulting to project-level for: " + ", ".join(PROJECT_TARGETS))
    return chosen


def _check_fastmcp(log: Logger) -> None:
    try:
        import fastmcp  # noqa: F401
    except ImportError:
        log("")
        log("Note: the MCP server needs `fastmcp`. Install it with:")
        log("      pip install -e \".[mcp]\"")


# --- public API ------------------------------------------------------------
def run_install(
    targets: Optional[List[str]] = None,
    project_dir: Optional[str] = None,
    write_agents: bool = True,
    antigravity_global: bool = False,
    log: Logger = print,
) -> bool:
    project = Path(project_dir or os.getcwd()).resolve()
    if not SKILLS_SRC.is_dir():
        log(f"[error] skills source not found at {SKILLS_SRC}")
        return False

    log("=" * 60)
    log(f"  Mobility Toolkit installer  |  project: {project}")
    log("=" * 60)

    chosen = _resolve_targets(targets, project, log)
    if not chosen:
        log("[error] no valid targets selected.")
        return False

    for t in chosen:
        if t == "antigravity":
            install_antigravity(project, log, use_global=antigravity_global)
        else:
            _INSTALLERS[t](project, log)

    if write_agents and any(t in PROJECT_TARGETS for t in chosen):
        _write_agents_md(project, log)

    _check_fastmcp(log)

    log("")
    log("Done. Verify with:  mobility-toolkit doctor")
    return True


def run_uninstall(
    targets: Optional[List[str]] = None,
    project_dir: Optional[str] = None,
    log: Logger = print,
) -> bool:
    project = Path(project_dir or os.getcwd()).resolve()
    chosen = list(ALL_TARGETS) if (not targets or targets == ["all"]) else [t for t in targets if t in ALL_TARGETS]
    log(f"Uninstalling targets: {', '.join(chosen)}  (project: {project})")

    for t in chosen:
        if t == "claude":
            _remove_skills(project / ".claude" / "skills", log)
            _json_unset_mcp(project / ".mcp.json", "mcpServers", log)
        elif t == "opencode":
            _remove_skills(project / ".opencode" / "skills", log)
            _json_unset_mcp(project / "opencode.json", "mcp", log)
        elif t == "codex":
            _remove_skills(project / ".agents" / "skills", log)
            _remove_codex_toml(project / ".codex" / "config.toml", log)
        elif t == "antigravity":
            # project-level (.agents/) and global (~/.gemini) are both cleaned
            _remove_skills(project / ".agents" / "skills", log)
            _json_unset_mcp(project / ".agents" / "mcp_config.json", "mcpServers", log)
            home = Path.home()
            _remove_skills(home / ".gemini" / "skills", log)
            _json_unset_mcp(home / ".gemini" / "config" / "mcp_config.json", "mcpServers", log)

    _remove_agents_block(project, log)
    log("Uninstall complete.")
    return True


def run_status(project_dir: Optional[str] = None, log: Logger = print) -> dict:
    project = Path(project_dir or os.getcwd()).resolve()
    checks = {
        "claude": [project / ".claude" / "skills" / SKILL_NAMES[0], project / ".mcp.json"],
        "opencode": [project / ".opencode" / "skills" / SKILL_NAMES[0], project / "opencode.json"],
        "codex": [project / ".agents" / "skills" / SKILL_NAMES[0], project / ".codex" / "config.toml"],
        "antigravity": [project / ".agents" / "skills" / SKILL_NAMES[0], project / ".agents" / "mcp_config.json"],
    }
    status = {}
    log(f"Install status  (project: {project})")
    for agent, (skills_path, mcp_path) in checks.items():
        skills_ok = skills_path.exists()
        mcp_ok = mcp_path.exists() and MCP_NAME in mcp_path.read_text(encoding="utf-8", errors="ignore")
        status[agent] = {"skills": skills_ok, "mcp": mcp_ok}
        log(f"  {agent:12s} skills={'yes' if skills_ok else 'no ':3s}  mcp={'yes' if mcp_ok else 'no'}")
    return status


# --- backward-compatible shim ---------------------------------------------
def install_skills(is_local: bool) -> None:
    """Legacy entry kept for older callers; routes to the new project installer."""
    run_install(targets=None, project_dir=os.getcwd())
