"""Project-level installer.

Wires the mobility_toolkit skills + MCP server into AI coding agents:

  - Claude Code   project: .claude/skills/   +  .mcp.json
  - opencode      project: .opencode/skills/ +  opencode.json   (also reads .claude/skills/)
  - Codex         project: .agents/skills/   +  .codex/config.toml
  - Antigravity   project: .agents/skills/   +  .agents/mcp_config.json
                  (Antigravity 2.0; --antigravity-global targets ~/.gemini instead)

All four agents support per-project config, so the default install is fully
project-level. Note `.agents/skills/` is shared by Codex and Antigravity 2.0.
Skills are the primary artifact; the MCP server is wired as the universal
fallback (every supported agent speaks MCP).
"""

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Callable, List, Optional

# --- locations -------------------------------------------------------------
PACKAGE_DIR = Path(__file__).resolve().parent          # .../mobility_toolkit/mobility_toolkit
REPO_ROOT = PACKAGE_DIR.parent                         # importable root (clone root or site-packages)
SKILLS_SRC = PACKAGE_DIR / "skills"                    # skills ship inside the package (wheel-installable)

# Skills, grouped by the three-layer model (see AGENTS.md):
#   L1 model -> L2 algebra -> L3 physics.
SKILL_NAMES = [
    "mt-translate",   # L1->L2  stabilizer model -> ring/matrix/variables
    "mt-homology",    # L1->L2  Ext module + Krull dim (+ attached L3 class)
    "mt-classify",    # L2->L3  Krull dim -> mobility class (pure)
    "mt-mobility",    # L2->L3  annihilator generators -> true mobility dimension
    "mt-gsd",         # L1->L3  GSD + periodicities on a torus
    "mt-fusion",      # L1->L3  fusion interference under shifts
    "mt-models",      # L1<->L3 model/property registry
    "mt-doctor",      # infra   Macaulay2 backend diagnostic
]

# --- MCP server invocation -------------------------------------------------
MCP_NAME = "mobility_toolkit"
MCP_COMMAND = sys.executable                           # pin the interpreter that has the package
MCP_ARGS = ["-m", "mobility_toolkit.mcp_server"]

# Upstream source used by `mobility-toolkit self-update`.
GIT_URL = "git+https://github.com/Misaka16384/mobility-toolkit.git"

PROJECT_TARGETS = ["claude", "codex", "opencode", "antigravity"]  # all support per-project config
ALL_TARGETS = list(PROJECT_TARGETS)

_BOOTSTRAP_MARKER = "mobility_toolkit path bootstrap"
AGENTS_BLOCK_START = "<!-- mobility-toolkit:start -->"
AGENTS_BLOCK_END = "<!-- mobility-toolkit:end -->"

Logger = Callable[[str], None]


# --- skill copying ---------------------------------------------------------
def _bootstrap_header() -> str:
    """A self-locating header injected into copied skill scripts so they can
    `import mobility_toolkit` even when run by a Python that has not pip-installed
    the package (the scripts get copied away from the repo)."""
    return (
        f"# >>> {_BOOTSTRAP_MARKER} (auto-generated by `mobility-toolkit install`) >>>\n"
        f"import sys as _mt_sys\n"
        f"_mt_sys.path.insert(0, r\"{REPO_ROOT}\")\n"
        f"# <<< {_BOOTSTRAP_MARKER} <<<\n\n"
    )


def _copy_skills(dest_root: Path, log: Logger) -> int:
    dest_root.mkdir(parents=True, exist_ok=True)
    count = 0
    for name in SKILL_NAMES:
        src = SKILLS_SRC / name
        if not src.is_dir():
            log(f"  ! skill source missing: {src}")
            continue
        dst = dest_root / name
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        scripts_dir = dst / "scripts"
        if scripts_dir.is_dir():
            for script in scripts_dir.glob("*.py"):
                text = script.read_text(encoding="utf-8")
                if _BOOTSTRAP_MARKER not in text:
                    script.write_text(_bootstrap_header() + text, encoding="utf-8")
        count += 1
    log(f"  + {count} skills -> {dest_root}")
    return count


def _remove_skills(dest_root: Path, log: Logger) -> None:
    removed = 0
    for name in SKILL_NAMES:
        dst = dest_root / name
        if dst.exists():
            shutil.rmtree(dst)
            removed += 1
    if removed:
        log(f"  - removed {removed} skills from {dest_root}")


# --- JSON config helpers ---------------------------------------------------
def _load_json(path: Path) -> dict:
    if path.exists():
        try:
            return json.loads(path.read_text(encoding="utf-8") or "{}")
        except json.JSONDecodeError:
            return {}
    return {}


def _save_json(path: Path, data: dict, log: Logger) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    log(f"  + MCP config -> {path}")


def _json_set_mcp(path: Path, parent_key: str, entry: dict, log: Logger) -> None:
    data = _load_json(path)
    data.setdefault(parent_key, {})[MCP_NAME] = entry
    _save_json(path, data, log)


def _json_unset_mcp(path: Path, parent_key: str, log: Logger) -> None:
    if not path.exists():
        return
    data = _load_json(path)
    if parent_key in data and MCP_NAME in data[parent_key]:
        del data[parent_key][MCP_NAME]
        _save_json(path, data, log)
        log(f"  - removed MCP entry from {path}")


# --- Codex TOML helpers (no tomli_w dependency) ----------------------------
def _toml_block() -> str:
    args_toml = ", ".join(f'"{a}"' for a in MCP_ARGS)
    # single-quoted TOML literal string avoids backslash escaping on Windows paths
    return (
        f"\n[mcp_servers.{MCP_NAME}]\n"
        f"command = '{MCP_COMMAND}'\n"
        f"args = [{args_toml}]\n"
    )


def _merge_codex_toml(path: Path, log: Logger) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    header = f"[mcp_servers.{MCP_NAME}]"
    if header in existing:
        log(f"  = MCP already present in {path}")
        return
    with path.open("a", encoding="utf-8") as f:
        f.write(_toml_block())
    log(f"  + MCP config -> {path} ([mcp_servers.{MCP_NAME}])")


def _remove_codex_toml(path: Path, log: Logger) -> None:
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    header = f"[mcp_servers.{MCP_NAME}]"
    if header not in text:
        return
    lines = text.splitlines(keepends=True)
    out, skipping = [], False
    for line in lines:
        stripped = line.strip()
        if stripped == header:
            skipping = True
            continue
        if skipping and stripped.startswith("[") and stripped.endswith("]"):
            skipping = False
        if not skipping:
            out.append(line)
    path.write_text("".join(out).rstrip() + "\n", encoding="utf-8")
    log(f"  - removed MCP block from {path}")


# --- AGENTS.md managed block ----------------------------------------------
def _agents_block() -> str:
    return (
        f"{AGENTS_BLOCK_START}\n"
        "## mobility_toolkit\n\n"
        "Homological-algebra toolkit for excitation-mobility properties of "
        "translation-invariant stabilizer codes (backed by Macaulay2).\n\n"
        "Skills are organized by three layers -- L1 model, L2 algebra, L3 physics -- "
        "each skill being an edge between two layers:\n"
        "- L1->L2: `mt-translate`, `mt-homology`\n"
        "- L2->L3: `mt-classify`, `mt-mobility`\n"
        "- L1->L3: `mt-gsd`, `mt-fusion`\n"
        "- store/infra: `mt-models`, `mt-doctor`\n"
        "Each skill bundles a script run directly, e.g. `python scripts/<name>.py < input.json`.\n\n"
        "Optionally also available as MCP server `mobility_toolkit` "
        "(install with `mobility-toolkit install --mcp`).\n\n"
        "Run `mobility-toolkit doctor` to verify the Macaulay2 backend; "
        "`mobility-toolkit self-update` to pull the latest version and refresh "
        "these skills.\n"
        f"{AGENTS_BLOCK_END}"
    )


def _write_agents_md(project: Path, log: Logger) -> None:
    path = project / "AGENTS.md"
    block = _agents_block()
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if AGENTS_BLOCK_START in text and AGENTS_BLOCK_END in text:
            pre = text.split(AGENTS_BLOCK_START)[0].rstrip()
            post = text.split(AGENTS_BLOCK_END, 1)[1].lstrip()
            text = (pre + "\n\n" + block + ("\n\n" + post if post else "\n")).rstrip() + "\n"
        else:
            text = text.rstrip() + "\n\n" + block + "\n"
    else:
        text = "# AGENTS\n\n" + block + "\n"
    path.write_text(text, encoding="utf-8")
    log(f"  + AGENTS.md -> {path}")


def _remove_agents_block(project: Path, log: Logger) -> None:
    path = project / "AGENTS.md"
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    if AGENTS_BLOCK_START in text and AGENTS_BLOCK_END in text:
        pre = text.split(AGENTS_BLOCK_START)[0].rstrip()
        post = text.split(AGENTS_BLOCK_END, 1)[1].lstrip()
        new = (pre + ("\n\n" + post if post else "")).rstrip() + "\n"
        path.write_text(new if new.strip() else "", encoding="utf-8")
        log(f"  - removed AGENTS.md block from {path}")


# --- per-agent installers --------------------------------------------------
# Skills are always installed; the MCP config is written only when with_mcp=True
# (MCP is opt-in -- the default install is skills-only, scripts called directly).
def install_claude(project: Path, log: Logger, with_mcp: bool = False) -> None:
    log("[claude] project-level (.claude/)")
    _copy_skills(project / ".claude" / "skills", log)
    if with_mcp:
        _json_set_mcp(project / ".mcp.json", "mcpServers", {"command": MCP_COMMAND, "args": MCP_ARGS}, log)


def install_opencode(project: Path, log: Logger, with_mcp: bool = False) -> None:
    log("[opencode] project-level (.opencode/)")
    _copy_skills(project / ".opencode" / "skills", log)
    if with_mcp:
        cfg = project / "opencode.json"
        data = _load_json(cfg)
        data.setdefault("$schema", "https://opencode.ai/config.json")
        data.setdefault("mcp", {})[MCP_NAME] = {
            "type": "local",
            "command": [MCP_COMMAND] + MCP_ARGS,
            "enabled": True,
        }
        _save_json(cfg, data, log)


def install_codex(project: Path, log: Logger, with_mcp: bool = False) -> None:
    log("[codex] project-level (.agents/, .codex/)")
    _copy_skills(project / ".agents" / "skills", log)
    if with_mcp:
        _merge_codex_toml(project / ".codex" / "config.toml", log)


def install_antigravity(project: Path, log: Logger, use_global: bool = False, with_mcp: bool = False) -> None:
    if use_global:
        home = Path.home()
        log("[antigravity] GLOBAL ~/.gemini")
        _copy_skills(home / ".gemini" / "skills", log)
        if with_mcp:
            _json_set_mcp(
                home / ".gemini" / "config" / "mcp_config.json",
                "mcpServers",
                {"command": MCP_COMMAND, "args": MCP_ARGS},
                log,
            )
    else:
        log("[antigravity] project-level (.agents/ — shared with Codex skills)")
        _copy_skills(project / ".agents" / "skills", log)
        if with_mcp:
            _json_set_mcp(
                project / ".agents" / "mcp_config.json",
                "mcpServers",
                {"command": MCP_COMMAND, "args": MCP_ARGS},
                log,
            )


_INSTALLERS = {
    "claude": install_claude,
    "codex": install_codex,
    "opencode": install_opencode,
    # antigravity is handled explicitly in run_install (needs the --antigravity-global flag)
}


# --- detection -------------------------------------------------------------
def detect_agents(project: Path) -> List[str]:
    found = []
    if (project / ".claude").exists() or shutil.which("claude"):
        found.append("claude")
    if (project / ".codex").exists() or (project / ".agents").exists() or shutil.which("codex"):
        found.append("codex")
    if (project / ".opencode").exists() or (project / "opencode.json").exists() or shutil.which("opencode"):
        found.append("opencode")
    if (project / ".agents").exists() or (Path.home() / ".gemini").exists() \
            or shutil.which("antigravity") or shutil.which("agy"):
        found.append("antigravity")
    return found


def _resolve_targets(targets: Optional[List[str]], project: Path, log: Logger) -> List[str]:
    if targets and targets != ["all"]:
        return [t for t in targets if t in ALL_TARGETS]
    if targets == ["all"]:
        return list(ALL_TARGETS)
    detected = list(dict.fromkeys(detect_agents(project)))
    chosen = detected or list(PROJECT_TARGETS)
    if detected:
        log(f"Detected agents: {', '.join(detected)}")
    else:
        log("No agents detected; defaulting to project-level for: " + ", ".join(PROJECT_TARGETS))
    return chosen


def _check_fastmcp(log: Logger) -> None:
    try:
        import fastmcp  # noqa: F401
    except ImportError:
        log("")
        log("Note: the MCP server needs `fastmcp`. Install it with:")
        log("      pip install -e \".[mcp]\"")


# --- public API ------------------------------------------------------------
def run_install(
    targets: Optional[List[str]] = None,
    project_dir: Optional[str] = None,
    write_agents: bool = True,
    antigravity_global: bool = False,
    with_mcp: bool = False,
    log: Logger = print,
) -> bool:
    project = Path(project_dir or os.getcwd()).resolve()
    if not SKILLS_SRC.is_dir():
        log(f"[error] skills source not found at {SKILLS_SRC}")
        return False

    log("=" * 60)
    log(f"  Mobility Toolkit installer  |  project: {project}")
    log(f"  mode: skills{' + MCP' if with_mcp else ' only (scripts called directly; pass --mcp to also wire MCP)'}")
    log("=" * 60)

    chosen = _resolve_targets(targets, project, log)
    if not chosen:
        log("[error] no valid targets selected.")
        return False

    for t in chosen:
        if t == "antigravity":
            install_antigravity(project, log, use_global=antigravity_global, with_mcp=with_mcp)
        else:
            _INSTALLERS[t](project, log, with_mcp)

    if write_agents and any(t in PROJECT_TARGETS for t in chosen):
        _write_agents_md(project, log)

    if with_mcp:
        _check_fastmcp(log)

    log("")
    log("Done. Verify with:  mobility-toolkit doctor")
    return True


def run_interactive(project_dir: Optional[str] = None, log: Logger = print) -> bool:
    """Interactive install wizard (used when `install` runs in a TTY)."""
    project = Path(project_dir or os.getcwd()).resolve()

    def ask(prompt: str, default: str = "") -> str:
        try:
            ans = input(prompt).strip()
        except EOFError:
            return default
        return ans or default

    log("=" * 60)
    log("  Mobility Toolkit — interactive install")
    log("=" * 60)
    log(f"Project folder : {project}")

    # backend status (informational)
    try:
        from mobility_toolkit.engine import describe_m2_backend
        b = describe_m2_backend()
        log(f"Macaulay2      : {b['strategy']} "
            f"({'available' if b['available'] else 'NOT FOUND — run `mobility-toolkit doctor`'})")
    except Exception:
        pass

    # 1. agents
    detected = list(dict.fromkeys(detect_agents(project)))
    default_sel = detected or list(PROJECT_TARGETS)
    log("\nAgents to install for:")
    for i, t in enumerate(ALL_TARGETS, 1):
        log(f"  {i}. {t}{'   (detected)' if t in detected else ''}")
    raw = ask(f"Select [comma-separated numbers, Enter = {', '.join(default_sel)}]: ")
    if raw:
        idxs = [int(x) for x in raw.replace(" ", "").split(",") if x.isdigit() and 1 <= int(x) <= len(ALL_TARGETS)]
        chosen = [ALL_TARGETS[i - 1] for i in idxs] or default_sel
    else:
        chosen = default_sel

    # 2. MCP
    with_mcp = ask("Also wire the MCP server? [y/N]: ").lower() in ("y", "yes")

    # 3. antigravity scope
    ag_global = False
    if "antigravity" in chosen:
        ag_global = ask("Antigravity scope — [P]roject (.agents/) or [g]lobal (~/.gemini)? [P/g]: ").lower() in ("g", "global")

    # 4. confirm
    log("\nSummary:")
    log(f"  agents          : {', '.join(chosen)}")
    log(f"  MCP server      : {'yes' if with_mcp else 'no (skills only — scripts called directly)'}")
    if "antigravity" in chosen:
        log(f"  Antigravity     : {'global (~/.gemini)' if ag_global else 'project (.agents/)'}")
    if ask("\nProceed? [Y/n]: ", default="y").lower() in ("n", "no"):
        log("Aborted.")
        return False

    log("")
    return run_install(
        targets=chosen,
        project_dir=str(project),
        with_mcp=with_mcp,
        antigravity_global=ag_global,
        log=log,
    )


def run_uninstall(
    targets: Optional[List[str]] = None,
    project_dir: Optional[str] = None,
    log: Logger = print,
) -> bool:
    project = Path(project_dir or os.getcwd()).resolve()
    chosen = list(ALL_TARGETS) if (not targets or targets == ["all"]) else [t for t in targets if t in ALL_TARGETS]
    log(f"Uninstalling targets: {', '.join(chosen)}  (project: {project})")

    for t in chosen:
        if t == "claude":
            _remove_skills(project / ".claude" / "skills", log)
            _json_unset_mcp(project / ".mcp.json", "mcpServers", log)
        elif t == "opencode":
            _remove_skills(project / ".opencode" / "skills", log)
            _json_unset_mcp(project / "opencode.json", "mcp", log)
        elif t == "codex":
            _remove_skills(project / ".agents" / "skills", log)
            _remove_codex_toml(project / ".codex" / "config.toml", log)
        elif t == "antigravity":
            # project-level (.agents/) and global (~/.gemini) are both cleaned
            _remove_skills(project / ".agents" / "skills", log)
            _json_unset_mcp(project / ".agents" / "mcp_config.json", "mcpServers", log)
            home = Path.home()
            _remove_skills(home / ".gemini" / "skills", log)
            _json_unset_mcp(home / ".gemini" / "config" / "mcp_config.json", "mcpServers", log)

    _remove_agents_block(project, log)
    log("Uninstall complete.")
    return True


def run_status(project_dir: Optional[str] = None, log: Logger = print) -> dict:
    project = Path(project_dir or os.getcwd()).resolve()
    checks = {
        "claude": [project / ".claude" / "skills" / SKILL_NAMES[0], project / ".mcp.json"],
        "opencode": [project / ".opencode" / "skills" / SKILL_NAMES[0], project / "opencode.json"],
        "codex": [project / ".agents" / "skills" / SKILL_NAMES[0], project / ".codex" / "config.toml"],
        "antigravity": [project / ".agents" / "skills" / SKILL_NAMES[0], project / ".agents" / "mcp_config.json"],
    }
    status = {}
    log(f"Install status  (project: {project})")
    for agent, (skills_path, mcp_path) in checks.items():
        skills_ok = skills_path.exists()
        mcp_ok = mcp_path.exists() and MCP_NAME in mcp_path.read_text(encoding="utf-8", errors="ignore")
        status[agent] = {"skills": skills_ok, "mcp": mcp_ok}
        log(f"  {agent:12s} skills={'yes' if skills_ok else 'no ':3s}  mcp={'yes' if mcp_ok else 'no'}")
    return status


# --- self-update -----------------------------------------------------------
def detect_install_mode() -> str:
    """How this package was installed, inferred from where it lives on disk.

    - ``"git"``   : an editable clone — ``REPO_ROOT`` is a git working tree
                    (``pip install -e .``); update by ``git pull``.
    - ``"wheel"`` : a wheel install in site-packages (``pipx``/``pip`` from the
                    git URL); update by re-running pip against that interpreter.
    """
    if (REPO_ROOT / ".git").is_dir() and (REPO_ROOT / "pyproject.toml").is_file():
        return "git"
    return "wheel"


def _update_command(mode: str) -> List[str]:
    """The subprocess that pulls the latest code for the given install mode."""
    if mode == "git":
        return ["git", "-C", str(REPO_ROOT), "pull", "--ff-only"]
    # Reinstall our package (only) into the SAME interpreter/venv. We use
    # `sys.executable -m pip` rather than `pipx` so this also works inside a
    # pipx-managed venv WITHOUT recreating it -- recreating the venv would try
    # to delete the running python.exe and fail on Windows. `--force-reinstall`
    # is required because the version string is static, so a plain `--upgrade`
    # sees 0.1.0 == 0.1.0 and skips the new commits.
    return [
        sys.executable, "-m", "pip", "install",
        "--upgrade", "--force-reinstall", "--no-deps", GIT_URL,
    ]


def run_self_update(
    project_dir: Optional[str] = None,
    with_mcp: Optional[bool] = None,
    refresh: bool = True,
    dry_run: bool = False,
    log: Logger = print,
) -> bool:
    """Pull the latest toolkit, then refresh the current project's skills.

    The project refresh re-installs exactly the agents already present in the
    project and preserves its MCP setup, unless ``with_mcp`` is given explicitly.
    """
    project = Path(project_dir or os.getcwd()).resolve()
    mode = detect_install_mode()
    cmd = _update_command(mode)

    # Look at what the project currently has so we refresh like-for-like.
    status = run_status(project_dir=str(project), log=lambda *_: None)
    installed = [a for a, v in status.items() if v["skills"]]
    refresh_targets = installed or None          # None -> auto-detect/default
    if with_mcp is None:
        with_mcp = any(v["mcp"] for v in status.values())

    log("=" * 60)
    log("  Mobility Toolkit — self-update")
    log("=" * 60)
    log(f"  install mode : {'editable clone (git pull)' if mode == 'git' else 'wheel (pip reinstall from git)'}")
    log(f"  source       : {REPO_ROOT if mode == 'git' else GIT_URL}")
    log(f"  project      : {project}")
    log(f"  step 1/2     : update package  ->  {' '.join(cmd)}")
    if refresh:
        tdesc = ", ".join(installed) if installed else "auto-detect"
        log(f"  step 2/2     : refresh skills ({tdesc}; mcp={'yes' if with_mcp else 'no'})")
    else:
        log("  step 2/2     : (skipped: --no-refresh)")

    if dry_run:
        log("\n[dry-run] no changes made.")
        return True

    # --- step 1: update the package -----------------------------------------
    log("\n[1/2] updating package ...")
    try:
        proc = subprocess.run(cmd, cwd=(str(REPO_ROOT) if mode == "git" else None))
    except FileNotFoundError as exc:
        tool = "git" if mode == "git" else "pip"
        log(f"[error] could not launch {tool}: {exc}")
        return False
    if proc.returncode != 0:
        log(f"[error] package update failed (exit {proc.returncode}).")
        if mode == "git":
            log(f"        Resolve the git state in {REPO_ROOT} and retry "
                f"(uncommitted changes block a fast-forward pull).")
        else:
            log("        Try manually:  " + " ".join(cmd))
        return False
    log("[1/2] package updated.")

    # --- step 2: refresh the current project's skills -----------------------
    if not refresh:
        log("\nDone (package only). Re-run `mobility-toolkit install` inside a "
            "project to refresh its skills.")
        return True

    # _copy_skills reads the skill sources from disk, which the step-1 update
    # just refreshed in place (same paths), so an in-process refresh picks up
    # the new content even though this process still holds the old modules.
    log("\n[2/2] refreshing project skills ...")
    ok = run_install(
        targets=refresh_targets,
        project_dir=str(project),
        with_mcp=with_mcp,
        log=log,
    )
    if ok:
        log("\nSelf-update complete.  Verify with:  mobility-toolkit doctor")
    return ok


