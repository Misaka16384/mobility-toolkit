r"""Exact one-sided contraction of a Laurent submodule.

Let

.. math::

   A = \mathbf F_p[u_1^{\pm1},\ldots,u_r^{\pm1}],\qquad
   S=A[n],\qquad R=A[n,n^{-1}].

For a Laurent submodule ``L <= R^m`` this module computes

.. math::

   L_H = L\cap S^m.

Each input column is first multiplied by its own smallest power of ``n`` that
clears negative depth.  These column shifts are units over ``R`` and therefore
do not change ``L``.  If ``N <= S^m`` is the module generated by the cleared
columns, then the actual contraction is

.. math::

   L_H = N:n^\infty.

The second step is essential: clearing columns is not, by itself, a module
intersection.  Macaulay2 computes the saturation over the exact quotient-ring
presentation of ``A[n]``.  A second Laurent ring with ``n`` inverted is used
to verify that ``N`` and the returned saturation have identical localization.

Only a uniform prime coefficient field and free tangent translations are
supported here.  This file does not construct the boundary Pauli quotient
``P_boundary`` and makes no claim about generic composite coefficients.
"""

