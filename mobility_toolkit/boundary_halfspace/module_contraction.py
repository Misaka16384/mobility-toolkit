PolynomialColumn = Tuple[TangentDepthPolynomial, ...]


def _integer(value: int, name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError(f"{name} must be an integer")
    return value


def _is_prime(value: int) -> bool:
    if value < 2:
        return False
    if value == 2:
        return True
    if value % 2 == 0:
        return False
    divisor = 3
    while divisor * divisor <= value:
        if value % divisor == 0:
            return False
        divisor += 2
    return True


@dataclass(frozen=True)
class LaurentHalfSpaceSubmodule:
    """Finite Laurent generators of a submodule of ``R^ambient_rank``."""

    coefficient_modulus: int
    normal: PrimitiveNormal
    ambient_rank: int
    generator_columns: Tuple[PolynomialColumn, ...] = ()

    SCHEMA_ID = "mobility_toolkit.laurent_halfspace_submodule.v1"

    def __post_init__(self) -> None:
        modulus = _integer(self.coefficient_modulus, "coefficient_modulus")
        if not _is_prime(modulus):
            raise ValueError(
                "half-space module contraction requires a uniform prime coefficient field"
            )
        rank = _integer(self.ambient_rank, "ambient_rank")
        if rank <= 0:
            raise ValueError("ambient_rank must be positive")
        columns = tuple(tuple(column) for column in self.generator_columns)
        for column in columns:
            if len(column) != rank:
                raise ValueError("generator column length must equal ambient_rank")
            for entry in column:
                if not isinstance(entry, TangentDepthPolynomial):
                    raise TypeError(
                        "generator entries must be TangentDepthPolynomial objects"
                    )
                if entry.coefficient_modulus != modulus:
                    raise ValueError("generator coefficient moduli differ")
                if entry.normal != self.normal:
                    raise ValueError("generator half-space normals differ")
                if entry.torsion_invariants:
                    raise ValueError(
                        "half-space module contraction currently supports free "
                        "tangent translations only"
                    )
        object.__setattr__(self, "coefficient_modulus", modulus)
        object.__setattr__(self, "ambient_rank", rank)
        object.__setattr__(self, "generator_columns", columns)

    @property
    def tangent_rank(self) -> int:
        return self.normal.dimension - 1

    def to_canonical_dict(self) -> dict:
        return {
            "ambient_rank": self.ambient_rank,
            "coefficient_modulus": self.coefficient_modulus,
            "generator_columns": self.generator_columns,
            "normal": self.normal,
            "schema": self.SCHEMA_ID,
        }


@dataclass(frozen=True)
class HalfSpaceContractionCertificate:
    """Machine-checked evidence for ``L cap S^m = N:n^infinity``."""

    column_depth_shifts: Tuple[int, ...]
    cleared_support_nonnegative: bool
    saturation_idempotent: bool
    cleared_module_contained_in_saturation: bool
    localization_equal: bool
    saturation_generator_count: int

    SCHEMA_ID = "mobility_toolkit.halfspace_contraction_certificate.v1"

    @property
    def verified(self) -> bool:
        return (
            self.cleared_support_nonnegative
            and self.saturation_idempotent
            and self.cleared_module_contained_in_saturation
            and self.localization_equal
        )

    def to_canonical_dict(self) -> dict:
        return {
            "cleared_support_nonnegative": self.cleared_support_nonnegative,
            "clearing_is_saturation": False,
            "column_depth_shifts": self.column_depth_shifts,
            "cleared_module_contained_in_saturation":
                self.cleared_module_contained_in_saturation,
            "localization_equal": self.localization_equal,
            "saturation_generator_count": self.saturation_generator_count,
            "saturation_idempotent": self.saturation_idempotent,
            "schema": self.SCHEMA_ID,
            "verified": self.verified,
        }


@dataclass(frozen=True)
class OneSidedSubmodule:
    """Generators of the exact contracted module over ``A[n]``."""

    coefficient_modulus: int
    normal: PrimitiveNormal
    ambient_rank: int
    generator_columns: Tuple[PolynomialColumn, ...]
    certificate: HalfSpaceContractionCertificate

    SCHEMA_ID = "mobility_toolkit.one_sided_submodule.v1"

    def __post_init__(self) -> None:
        columns = tuple(tuple(column) for column in self.generator_columns)
        if any(len(column) != self.ambient_rank for column in columns):
            raise ValueError("one-sided generator column rank mismatch")
        for column in columns:
            for entry in column:
                if entry.coefficient_modulus != self.coefficient_modulus:
                    raise ValueError("one-sided generator coefficient moduli differ")
                if entry.normal != self.normal:
                    raise ValueError("one-sided generator normals differ")
                if any(term.depth < 0 for term in entry.terms):
                    raise ValueError("one-sided generator has negative depth")
        object.__setattr__(
            self,
            "generator_columns",
            tuple(sorted(columns, key=canonical_json)),
        )

    def to_canonical_dict(self) -> dict:
        return {
            "ambient_rank": self.ambient_rank,
            "certificate": self.certificate,
            "coefficient_modulus": self.coefficient_modulus,
            "generator_columns": self.generator_columns,
            "normal": self.normal,
            "schema": self.SCHEMA_ID,
        }


def _column_minimum_depth(column: PolynomialColumn) -> int:
    depths = [
        term.depth
        for polynomial in column
        for term in polynomial.terms
    ]
    return min(depths) if depths else 0


def clear_submodule_columns(
    submodule: LaurentHalfSpaceSubmodule,
) -> Tuple[Tuple[PolynomialColumn, ...], Tuple[int, ...]]:
    """Clear every column by its smallest normal monomial.

    The returned module has the same span only after localizing at ``n``.  Its
    ``S``-span generally is *not* the requested contraction; callers must still
    saturate it.
    """

    if not isinstance(submodule, LaurentHalfSpaceSubmodule):
        raise TypeError("submodule must be LaurentHalfSpaceSubmodule")
    shifts = tuple(
        max(0, -_column_minimum_depth(column))
        for column in submodule.generator_columns
    )
    columns = tuple(
        tuple(entry.shift_depth(shift) for entry in column)
        for column, shift in zip(submodule.generator_columns, shifts)
    )
    return columns, shifts


def _render_polynomial(polynomial: TangentDepthPolynomial) -> str:
    if polynomial.is_zero:
        return "0"
    rendered = []
    for term in polynomial.terms:
        factors = []
        coefficient = term.coefficient % polynomial.coefficient_modulus
        for index, exponent in enumerate(term.tangent_exponents, 1):
            if exponent == 0:
                continue
            variable = f"x{index}" if exponent > 0 else f"t{index}"
            power = abs(exponent)
            factors.append(variable if power == 1 else f"{variable}^{power}")
        if term.depth:
            factors.append("n" if term.depth == 1 else f"n^{term.depth}")
        if coefficient != 1 or not factors:
            factors.insert(0, str(coefficient))
        rendered.append("*".join(factors))
    return " + ".join(rendered)


def _matrix_expression(columns: Tuple[PolynomialColumn, ...], ambient_rank: int) -> str:
    if not columns:
        return f"map(S^{ambient_rank},S^0,0)"
    rows = []
    for row in range(ambient_rank):
        rows.append("{" + ",".join(_render_polynomial(column[row]) for column in columns) + "}")
    return "matrix{" + ",".join(rows) + "}"


def _m2_script(
    submodule: LaurentHalfSpaceSubmodule,
    cleared_columns: Tuple[PolynomialColumn, ...],
) -> str:
    tangent_variables = [
        variable
        for index in range(1, submodule.tangent_rank + 1)
        for variable in (f"x{index}", f"t{index}")
    ]
    polynomial_variables = tangent_variables + ["n"]
    inverse_relations = [
        f"x{index}*t{index}-1"
        for index in range(1, submodule.tangent_rank + 1)
    ]
    presentation_ideal = (
        "ideal(" + ",".join(inverse_relations) + ")"
        if inverse_relations
        else "ideal(0_P)"
    )
    localization_variables = tangent_variables + ["n", "ni"]
    localization_relations = inverse_relations + ["n*ni-1"]
    matrix = _matrix_expression(cleared_columns, submodule.ambient_rank)
    return "\n".join(
        (
            f"P = GF({submodule.coefficient_modulus})"
            f"[{','.join(polynomial_variables)},MonomialOrder=>GRevLex];",
            f"S = P/({presentation_ideal});",
            f"B = {matrix};",
            "N = image B;",
            "Sat = trim saturate(N, ideal(n));",
            "Sat2 = trim saturate(Sat, ideal(n));",
            "satIdempotent = isSubset(Sat,Sat2) and isSubset(Sat2,Sat);",
            "originalContained = isSubset(N,Sat);",
            f"PL = GF({submodule.coefficient_modulus})"
            f"[{','.join(localization_variables)},MonomialOrder=>GRevLex];",
            "T = PL/(ideal(" + ",".join(localization_relations) + "));",
            "NL = substitute(N,T);",
            "SatL = substitute(Sat,T);",
            "localizationEqual = isSubset(NL,SatL) and isSubset(SatL,NL);",
            'print("MT_HS:SAT_IDEMPOTENT:" | toString satIdempotent);',
            'print("MT_HS:ORIGINAL_CONTAINED:" | toString originalContained);',
            'print("MT_HS:LOCALIZATION_EQUAL:" | toString localizationEqual);',
            "G = gens Sat;",
            'print("MT_HS:ROWS:" | toString numRows G);',
            'print("MT_HS:COLS:" | toString numColumns G);',
            "if numColumns G > 0 then scan(0..numColumns G-1, c -> "
            "scan(0..numRows G-1, r -> "
            'print("MT_HS:ENTRY:" | toString r | ":" | toString c | ":" '
            "| toString G_(r,c))));",
        )
    )


def _marker(stdout: str, name: str) -> str:
    match = re.search(
        rf"^\s*MT_HS:{re.escape(name)}:(.*)$",
        stdout,
        flags=re.MULTILINE,
    )
    if match is None:
        raise RuntimeError(f"Macaulay2 output is missing marker {name!r}")
    return match.group(1).strip()


def _boolean_marker(stdout: str, name: str) -> bool:
    value = _marker(stdout, name).lower()
    if value not in {"true", "false"}:
        raise RuntimeError(f"Macaulay2 marker {name!r} is not boolean: {value!r}")
    return value == "true"


def _parse_entry(
    expression: str,
    modulus: int,
    normal: PrimitiveNormal,
) -> TangentDepthPolynomial:
    tangent_rank = normal.dimension - 1
    normalized = re.sub(r"\bn\b", f"x{tangent_rank + 1}", expression)
    parsed = _parse_laurent_poly(normalized, tangent_rank + 1, modulus)
    terms = []
    for exponents, coefficient in parsed.items():
        if exponents[-1] < 0:
            raise RuntimeError("Macaulay2 returned a negative-depth saturation generator")
        terms.append(
            TangentDepthTerm(
                coefficient,
                exponents[:-1],
                exponents[-1],
                (),
            )
        )
    return TangentDepthPolynomial(modulus, normal, (), tuple(terms))


def _parse_generators(
    stdout: str,
    submodule: LaurentHalfSpaceSubmodule,
) -> Tuple[PolynomialColumn, ...]:
    rows = int(_marker(stdout, "ROWS"))
    columns = int(_marker(stdout, "COLS"))
    if rows != submodule.ambient_rank:
        raise RuntimeError(
            "Macaulay2 saturation ambient rank differs from the requested module"
        )
    entries = {}
    for match in re.finditer(
        r"^\s*MT_HS:ENTRY:(\d+):(\d+):(.*)$",
        stdout,
        flags=re.MULTILINE,
    ):
        row, column = int(match.group(1)), int(match.group(2))
        entries[(row, column)] = _parse_entry(
            match.group(3).strip(),
            submodule.coefficient_modulus,
            submodule.normal,
        )
    expected = {(row, column) for column in range(columns) for row in range(rows)}
    if set(entries) != expected:
        raise RuntimeError("Macaulay2 saturation output has incomplete matrix entries")
    parsed = tuple(
        tuple(entries[(row, column)] for row in range(rows))
        for column in range(columns)
    )
    return tuple(sorted(parsed, key=canonical_json))


def contract_laurent_submodule(
    submodule: LaurentHalfSpaceSubmodule,
    *,
    timeout_seconds: float = 60.0,
    execute: Optional[Callable[[str, float], dict]] = None,
) -> ComputationResult:
    """Compute ``L cap A[n]^m`` exactly for a uniform-prime Laurent submodule."""

    if not isinstance(submodule, LaurentHalfSpaceSubmodule):
        raise TypeError("submodule must be LaurentHalfSpaceSubmodule")
    if not isinstance(timeout_seconds, (int, float)) or isinstance(timeout_seconds, bool):
        raise TypeError("timeout_seconds must be a positive number")
    if timeout_seconds <= 0 or not math.isfinite(float(timeout_seconds)):
        raise ValueError("timeout_seconds must be finite and positive")
    cleared_columns, shifts = clear_submodule_columns(submodule)
    script = _m2_script(submodule, cleared_columns)
    runner = execute or (
        lambda source, timeout: run_macaulay2(source, timeout_seconds=timeout)
    )
    backend_result = runner(script, float(timeout_seconds))
    if int(backend_result.get("exit_code", 1)) != 0:
        message = (
            backend_result.get("stderr")
            or backend_result.get("stdout")
            or "Macaulay2 saturation failed"
        )
        raise RuntimeError(f"Macaulay2 half-space contraction failed: {message}")
    stdout = str(backend_result.get("stdout", ""))
    generators = _parse_generators(stdout, submodule)
    certificate = HalfSpaceContractionCertificate(
        column_depth_shifts=shifts,
        cleared_support_nonnegative=all(
            term.depth >= 0
            for column in cleared_columns
            for entry in column
            for term in entry.terms
        ),
        saturation_idempotent=_boolean_marker(stdout, "SAT_IDEMPOTENT"),
        cleared_module_contained_in_saturation=_boolean_marker(
            stdout, "ORIGINAL_CONTAINED"
        ),
        localization_equal=_boolean_marker(stdout, "LOCALIZATION_EQUAL"),
        saturation_generator_count=len(generators),
    )
    if not certificate.verified:
        raise RuntimeError(
            "Macaulay2 returned a half-space contraction that failed its certificate"
        )
    value = OneSidedSubmodule(
        coefficient_modulus=submodule.coefficient_modulus,
        normal=submodule.normal,
        ambient_rank=submodule.ambient_rank,
        generator_columns=generators,
        certificate=certificate,
    )
    description = describe_m2_backend()
    return ComputationResult(
        operation="halfspace.contract_laurent_submodule",
        input_data=submodule,
        value=value,
        exactness=Exactness.CERTIFIED_EXACT,
        assumptions=(
            "finite Laurent generating set",
            "free tangent translation lattice",
            "uniform prime coefficient field",
        ),
        theorem_scope=(
            "Exact submodule contraction L cap A[n]^m = "
            "(cleared columns):n^infinity; no P_boundary construction."
        ),
        certificate_level=CertificateLevel.FULL,
        certificate=certificate,
        verification=(
            ("clearing_is_saturation", False),
            ("localization_equal", certificate.localization_equal),
            ("saturation_idempotent", certificate.saturation_idempotent),
        ),
        backend_provenance=BackendProvenance(
            backend="Macaulay2",
            algorithm="one-sided-module-contraction-by-normal-saturation",
            version="unprobed",
            parameters=(
                ("coefficient_modulus", submodule.coefficient_modulus),
                ("normal", submodule.normal.components),
                ("strategy", str(description.get("strategy", ""))),
                ("tangent_rank", submodule.tangent_rank),
            ),
        ),
        diagnostics=(
            "Columns are minimally cleared before module saturation.",
            "Equality after inverting the normal variable was checked in Macaulay2.",
        ),
        warnings=(
            "Column clearing alone is not module saturation.",
            "This result is L_H only; P_boundary and boundary quasi-symplectic "
            "quotients are outside this operation.",
        ),
    )


